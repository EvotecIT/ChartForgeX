namespace ChartForgeX.Core;

/// <summary>Built-in shapes shared by numeric point markers and their legends.</summary>
public enum ChartMarkerShape {
    /// <summary>A circle centered on the observation.</summary>
    Circle,
    /// <summary>A square centered on the observation.</summary>
    Square,
    /// <summary>A diamond centered on the observation.</summary>
    Diamond,
    /// <summary>An upward-pointing triangle centered on the observation.</summary>
    Triangle,
    /// <summary>A filled upright plus.</summary>
    Plus,
    /// <summary>A filled diagonal cross.</summary>
    Cross,
    /// <summary>A heart centered on the observation.</summary>
    Heart,
    /// <summary>A location pin contained within the marker's bounds.</summary>
    Pin,
    /// <summary>A five-point star centered on the observation.</summary>
    Star
}
