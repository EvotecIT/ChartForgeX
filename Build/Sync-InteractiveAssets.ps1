<#
.SYNOPSIS
    Regenerates the maintained interactive JavaScript assets.
.DESCRIPTION
    Joins the readable source fragments and uses the existing PowerForge Web
    JavaScript optimizer for interactive.js. Topology assets remain unoptimized.
    Ordinary .NET builds consume the checked-in assets and do not invoke this tool.
.PARAMETER Check
    Compares the generated bytes with the checked-in assets without changing them.
.PARAMETER PowerForgeCliPath
    Path to the existing pinned PowerForge.Web.Cli.dll used for website builds.
    The script does not build, install, restore, or download the optimizer.
.EXAMPLE
    ./Build/Sync-InteractiveAssets.ps1 -PowerForgeCliPath /path/to/PowerForge.Web.Cli.dll
.EXAMPLE
    ./Build/Sync-InteractiveAssets.ps1 -Check -PowerForgeCliPath /path/to/PowerForge.Web.Cli.dll
#>
param(
    [switch] $Check,
    [Parameter(Mandatory)]
    [string] $PowerForgeCliPath
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$PowerForgeCliPath = (Get-Item -LiteralPath $PowerForgeCliPath -ErrorAction Stop).FullName
if (-not [System.IO.File]::Exists($PowerForgeCliPath)) {
    throw 'PowerForgeCliPath must identify the existing PowerForge Web CLI assembly.'
}

$assets = @(
    @{
        Prelude = 'ChartForgeX.Interactivity.Html/Assets/adapter-localization.js'
        Source = 'ChartForgeX.Interactivity.Html/Assets/topology-interaction.source'
        Target = 'ChartForgeX.Interactivity.Html/Assets/topology-interaction.js'
    },
    @{
        Prelude = 'ChartForgeX.Interactivity.Html/Assets/adapter-localization.js'
        Source = 'ChartForgeX.Interactivity.Html/Assets/interactive.source'
        Target = 'ChartForgeX.Interactivity.Html/Assets/interactive.js'
        OptimizeJavaScript = $true
    }
)

function Join-AssetSource {
    param([string] $SourcePath)

    $parts = Get-ChildItem -Path $SourcePath -Filter '*.js' -File |
        Sort-Object Name

    if ($parts.Count -eq 0) {
        throw "No JavaScript source fragments found in '$SourcePath'."
    }

    $content = foreach ($part in $parts) {
        [System.IO.File]::ReadAllText($part.FullName).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n")
    }

    ($content -join "`n") + "`n"
}

function Optimize-JavaScriptAsset {
    param([string] $Content)

    # PowerForge owns optimization; this producer owns only its isolated input/output.
    $temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath()).TrimEnd([System.IO.Path]::DirectorySeparatorChar)
    $stage = Join-Path $temporaryRoot ('cfx-interactive-asset-' + [Guid]::NewGuid().ToString('N'))
    [void] [System.IO.Directory]::CreateDirectory($stage)
    $completed = $false
    try {
        $script = Join-Path $stage 'interactive.js'
        [System.IO.File]::WriteAllText($script, $Content, [System.Text.UTF8Encoding]::new($false))
        [System.IO.File]::WriteAllText((Join-Path $stage 'interactive.input.txt'), $Content, [System.Text.UTF8Encoding]::new($false))
        & dotnet $PowerForgeCliPath optimize --site-root $stage --minify-js --report-path optimization.json --json 2>&1 |
            Tee-Object -FilePath (Join-Path $stage 'optimization.log') | Out-Host
        if ($LASTEXITCODE -ne 0) {
            throw "PowerForge JavaScript optimization failed with exit code $LASTEXITCODE."
        }
        $report = Get-Content -LiteralPath (Join-Path $stage 'optimization.json') -Raw | ConvertFrom-Json
        if ($report.JsFileCount -ne 1 -or $report.JsMinifiedCount -ne 1) {
            throw 'PowerForge did not optimize the single interactive JavaScript asset.'
        }
        $optimized = [System.IO.File]::ReadAllText($script).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n")
        if ([string]::IsNullOrWhiteSpace($optimized)) {
            throw 'PowerForge returned an empty interactive JavaScript asset.'
        }
        $completed = $true
        return $optimized + "`n"
    } finally {
        if ($completed) {
            $directory = Get-Item -LiteralPath $stage -Force
            if ($directory.Parent.FullName -ne $temporaryRoot -or
                ($directory.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
                throw "Retaining optimizer output because its temporary directory changed: '$stage'."
            }
            foreach ($entry in Get-ChildItem -LiteralPath $stage -Force) {
                if ($entry.PSIsContainer -or ($entry.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
                    throw "Retaining optimizer output because it contains an unexpected directory or link: '$stage'."
                }
            }
            [System.IO.Directory]::Delete($stage, $true)
        } else {
            Write-Warning "Optimizer input, report and diagnostics are retained at '$stage'."
        }
    }
}

foreach ($asset in $assets) {
    $sourcePath = Join-Path $root $asset.Source
    $targetPath = Join-Path $root $asset.Target
    $generated = Join-AssetSource -SourcePath $sourcePath
    if ($asset.Prelude) {
        $preludePath = Join-Path $root $asset.Prelude
        $prelude = [System.IO.File]::ReadAllText($preludePath).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n")
        $generated = $prelude + "`n" + $generated
    }

    if ($asset.OptimizeJavaScript) {
        $generated = Optimize-JavaScriptAsset -Content $generated
    }

    if ($Check) {
        $current = [System.IO.File]::ReadAllText($targetPath).Replace("`r`n", "`n").Replace("`r", "`n")
        if ($current -ne $generated) {
            throw "Generated asset is out of date: $($asset.Target). Run Build/Sync-InteractiveAssets.ps1."
        }

        continue
    }

    [System.IO.File]::WriteAllText($targetPath, $generated, [System.Text.UTF8Encoding]::new($false))
}
